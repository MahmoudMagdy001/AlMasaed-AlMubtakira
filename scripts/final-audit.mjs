import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const rootDir = path.resolve(__dirname, '..')
const distDir = path.join(rootDir, 'dist')
const srcDir = path.join(rootDir, 'src')

console.log('=== Running Final Audit (09-natural-look-rules.md) ===\n')

// Prohibited terms per specification
const FORBIDDEN_AI_NAMES = [
  'claude',
  'anthropic',
  'openai',
  'chatgpt',
  'gemini',
  'copilot',
  'windsurf',
  'lovable',
  'bolt.new',
  'v0.dev',
  'lorem ipsum',
  'TODO:',
  'FIXME:',
  'Vite + React',
  'AI generated',
  'Generated by',
]

// Emoji detection regex (extended pictographic excluding standard typography marks like © U+00A9 and ® U+00AE)
const EMOJI_REGEX = /(?![\u00A9\u00AE])\p{Extended_Pictographic}/u

let violations = 0

function scanDirectory(dir, contextName, allowedFileFilter = () => true) {
  if (!fs.existsSync(dir)) return

  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules' || entry.name === '.git' || entry.name === '.vite') continue
      scanDirectory(fullPath, contextName, allowedFileFilter)
    } else if (allowedFileFilter(entry.name)) {
      const content = fs.readFileSync(fullPath, 'utf8')
      const lower = content.toLowerCase()
      const relPath = path.relative(rootDir, fullPath)

      // Skip test files and final audit itself
      if (relPath.includes('09-natural-look-rules') || relPath.includes('final-audit') || relPath.includes('__tests__') || relPath.includes('.test.')) {
        continue
      }

      // 1. Check forbidden terms
      for (const term of FORBIDDEN_AI_NAMES) {
        if (lower.includes(term.toLowerCase())) {
          console.error(`[VIOLATION: FORBIDDEN_TERM] "${term}" in ${relPath}`)
          violations++
        }
      }

      // Check Cursor editor mention (not CSS cursor property)
      if (/\bCursor\b/.test(content)) {
        // Exclude CSS class mentions or cursor: styles
        const lines = content.split('\n')
        for (let i = 0; i < lines.length; i++) {
          const line = lines[i]
          if (/\bCursor\b/.test(line) && !line.includes('cursor-') && !line.includes('cursor:')) {
            console.error(`[VIOLATION: AI TOOL MENTION] "Cursor" at ${relPath}:${i + 1}`)
            violations++
          }
        }
      }

      // 2. Check emojis in public code & HTML
      if (EMOJI_REGEX.test(content)) {
        // Ignore supabase-js vendor or node_modules
        if (!relPath.startsWith('docs') && !relPath.includes('vendor-supabase')) {
          console.warn(`[WARNING: EMOJI DETECTED] in ${relPath}`)
          violations++
        }
      }

      // 3. Check for leftover console.log in src/
      if (relPath.startsWith('src') && !relPath.includes('vite-env.d.ts')) {
        const consoleMatches = content.match(/console\.log\(/g) || []
        if (consoleMatches.length > 0) {
          console.warn(`[WARNING: CONSOLE.LOG] ${consoleMatches.length} instance(s) in ${relPath}`)
          violations++
        }
      }
    }
  }
}

// Scan src directory
console.log('--- Scanning src/ directory ---')
scanDirectory(srcDir, 'src', (name) => /\.(tsx?|jsx?|css|json)$/.test(name))

// Scan dist directory (built output)
console.log('--- Scanning dist/ directory ---')
scanDirectory(distDir, 'dist', (name) => /\.(html|js|css|json)$/.test(name))

console.log(`\n=================================================`)
console.log(`Final Audit Results: ${violations} violations found.`)
console.log(`=================================================\n`)

if (violations > 0) {
  process.exit(1)
} else {
  console.log('[SUCCESS] Repository and build output are 100% clean and studio-grade!')
}
